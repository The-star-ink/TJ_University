/***************************************************************************
  函数名称：menu_main
  功    能：整数性菜单选项
  输入参数：min,max，分别标定菜单的最小和最大值
  返 回 值：int back
  说    明：
***************************************************************************/
int menu_main(int min, int max) {
  while (1) {
    int back = _getch();
    back -= '0';
    if (back >= min && back <= max) {
      cout << back << endl;
      return back;
    }
  }
}

/***************************************************************************
  函数名称：menu_main
  功    能：字符性菜单选项
  输入参数：char min, char max ，分别标定菜单的最小和最大值
  返 回 值：int back
  说    明：统一转回int型返回,A/a对应1……
***************************************************************************/
int menu_main(char min, char max) {
  while (1) {
    char back = _getch();
    if (back >= min && back <= max) {
      cout << back << endl;
      back -= ('A' - 1);
      return back;
    }
  }
}