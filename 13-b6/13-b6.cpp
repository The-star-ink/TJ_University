#include <iostream>
using namespace std;

/***************************************************************************
  函数名称：f_sub
  功    能：打印传入的整型参数 x
  输入参数：x —— 待输出的整数
  返 回 值：无
  说    明：题目给定函数，作为“最终被调用的那一层”
***************************************************************************/
void f_sub(int x) { cout << "x = " << x << endl; }

/***************************************************************************
  函数名称：f_msg
  功    能：打印传入的字符串，并返回 f_sub 的函数指针
  输入参数：p —— 指向字符串常量的指针
  返 回 值：void(*)(int) 类型的函数指针（即 f_sub 的地址）
  说    明：新增函数，充当 f 数组元素所指向的“第一层函数”
***************************************************************************/
void (*f_msg(const char *p))(int x) {
  cout << "str = " << p << endl;
  return f_sub; // 函数名自动退化为 void(*)(int)
}

/***************************************************************************
  函数名称：main
  功    能：通过 f[0] 演示两段式（返回函数指针再调用）的调用过程
  输入参数：无
  返 回 值：0
  说    明：原声明行与两条调用语句保持不动，仅新增一行赋值
***************************************************************************/
int main() {
  void (*(*f[3])(const char *p))(int x);

  f[0] = f_msg; // 新增：把数组首元素指向 f_msg，消除野指针

  f[0]("Hello")(2);
  f[0]("Tongji")(7);

  return 0;
}
