#include <iomanip>
#include <iostream>
using namespace std;

#define STUDENT_NUM 4
#define SCORE_NUM 5

/* --- 不允许定义任何形式的全局变量 --- */

/***************************************************************************
  函数名称：average
  功    能：求第一门课的平均分
  输入参数：int (*score)[SCORE_NUM]  行指针，一行是一个学生的 5 门课成绩
  返 回 值：无
  说    明：只定义 1 个简单变量 + 1 个指针变量；
            第一门课的成绩位于每一行的首元素，故用 **p 取值，
            行与行之间用行指针 p 移动，全程不出现 [ ]
***************************************************************************/
void average(int (*score)[SCORE_NUM]) {
  double sum = 0;      /* 简单变量：总分 */
  int (*p)[SCORE_NUM]; /* 行指针：指向某个学生的一行 */

  for (p = score; p < score + STUDENT_NUM; p++) {
    sum += **p; /* **p 即该学生第 1 门课的成绩 */
  }

  cout << "第1门课平均分：" << sum / STUDENT_NUM << endl;
}

/***************************************************************************
  函数名称：fail
  功    能：找出有两门以上（含两门）课程不及格的学生，
            输出该学生的学号、每门课程的成绩及平均成绩
  输入参数：int (*score)[SCORE_NUM]
  返 回 值：无
  说    明：只定义 2 个简单变量 + 1 个行指针变量 + 1 个简单指针变量；
            外层用行指针 p 遍历学生，内层用简单指针 q 遍历一门门课
***************************************************************************/
void fail(int (*score)[SCORE_NUM]) {
  int count;           /* 简单变量：不及格门数 */
  double sum;          /* 简单变量：总分 */
  int (*p)[SCORE_NUM]; /* 行指针：指向某个学生的一行 */
  int *q;              /* 简单指针：指向某门课的成绩 */

  cout << "2门以上不及格的学生：" << endl;

  for (p = score; p < score + STUDENT_NUM; p++) {
    count = 0;
    for (q = *p; q < *p + SCORE_NUM; q++) /* *p 即该行首元素地址 */
    {
      if (*q < 60) {
        count++;
      }
    }

    if (count >= 2) {
      sum = 0;
      cout << "No：" << p - score + 1; /* 学号 = 行下标 + 1 */
      for (q = *p; q < *p + SCORE_NUM; q++) {
        cout << " " << *q;
        sum += *q;
      }
      cout << " 平均：" << sum / SCORE_NUM << endl;
    }
  }
}

/***************************************************************************
  函数名称：good
  功    能：找出平均成绩在 90 分以上（含 90）或全部课程成绩在 85 分
            以上（含 85）的学生
  输入参数：int (*score)[SCORE_NUM]
  返 回 值：无
  说    明：只定义 2 个简单变量 + 1 个行指针变量 + 1 个简单指针变量
***************************************************************************/
void good(int (*score)[SCORE_NUM]) {
  int count;           /* 简单变量：低于 85 分的门数 */
  double sum;          /* 简单变量：总分 */
  int (*p)[SCORE_NUM]; /* 行指针 */
  int *q;              /* 简单指针 */

  cout << "平均90以上或全部85以上的学生：" << endl;

  for (p = score; p < score + STUDENT_NUM; p++) {
    count = 0;
    sum = 0;
    for (q = *p; q < *p + SCORE_NUM; q++) {
      sum += *q;
      if (*q < 85) {
        count++;
      }
    }

    if (sum / SCORE_NUM >= 90 || count == 0) {
      cout << "No：" << p - score + 1;
      for (q = *p; q < *p + SCORE_NUM; q++) {
        cout << " " << *q;
      }
      cout << " 平均：" << sum / SCORE_NUM << endl;
    }
  }
}

/***************************************************************************
  函数名称：main
  功    能：输出初始信息，并依次调用 average、fail、good 三个函数
  输入参数：无
  返 回 值：0
  说    明：除预置二维数组外，只定义 1 个行指针变量 + 1 个简单指针变量
***************************************************************************/
int main() {
  int a[STUDENT_NUM][SCORE_NUM] = {
      {91, 81, 71, 61, 51},  // 第1个学生的1-5门课的成绩
      {92, 82, 72, 32, 52},  // 第2个学生的1-5门课的成绩
      {93, 83, 99, 80, 95},  // 第3个学生的1-5门课的成绩
      {97, 85, 87, 91, 88}}; // 第4个学生的1-5门课的成绩

  int (*p)[SCORE_NUM]; /* 行指针：一行一个学生 */
  int *q;              /* 简单指针：一行内逐门课 */

  cout << "初始信息：" << endl;
  for (p = a; p < a + STUDENT_NUM; p++) {
    cout << "No." << p - a + 1 << "的1-5门课成绩：";
    for (q = *p; q < *p + SCORE_NUM; q++) {
      cout << *q << " ";
    }
    cout << endl;
  }

  cout << endl;
  average(a); /* 求第一门课的平均分 */
  cout << endl;
  fail(a); /* 两门以上不及格的学生 */
  cout << endl;
  good(a); /* 平均 90 以上或全部 85 以上 */

  return 0;
}