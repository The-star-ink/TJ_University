#include <iomanip>
#include <iostream>
using namespace std;

#define STUDENT_NUM 4
#define SCORE_NUM 5

/* --- 不允许定义任何形式的全局变量 --- */

/***************************************************************************
  函数名称：average
  功    能：求第一门课的平均分
  输入参数：int (*score)[STUDENT_NUM]  行指针，一行是一门课 4 个学生的成绩
  返 回 值：无
  说    明：只定义 1 个简单变量 + 1 个指针变量；
            第一门课的成绩就是第 0 行的 4 个元素，在内存中连续存放，
            故用一个简单指针在该行内移动即可（本函数不涉及行的循环）
***************************************************************************/
void average(int (*score)[STUDENT_NUM]) {
  double sum = 0; /* 简单变量：总分 */
  int *q;         /* 简单指针：指向本行中的某个成绩 */

  for (q = *score; q < *score + STUDENT_NUM; q++) {
    sum += *q; /* 累加第 1 门课的 4 个成绩 */
  }

  cout << "第1门课平均分：" << sum / STUDENT_NUM << endl;
}

/***************************************************************************
  函数名称：fail
  功    能：找出有两门以上（含两门）课程不及格的学生，
            输出该学生的学号、每门课程的成绩及平均成绩
  输入参数：int (*score)[STUDENT_NUM]
  返 回 值：无
  说    明：只定义 3 个简单变量 + 1 个行指针变量 + 1 个简单指针变量；
            数组按“行=课程、列=学生”存放，故外层按学生（列下标 i）循环，
            内层用行指针 p 逐门课移动，q = *p + i 取第 i 个学生的成绩
***************************************************************************/
void fail(int (*score)[STUDENT_NUM]) {
  int i;                 /* 简单变量：学生列下标 */
  int count;             /* 简单变量：不及格门数 */
  double sum;            /* 简单变量：总分 */
  int (*p)[STUDENT_NUM]; /* 行指针：依次指向每一门课 */
  int *q;                /* 简单指针：指向某学生的某门课成绩 */

  cout << "2门以上不及格的学生：" << endl;

  for (i = 0; i < STUDENT_NUM; i++) {
    count = 0;
    sum = 0;
    for (p = score; p < score + SCORE_NUM; p++) /* 行指针逐门课移动 */
    {
      q = *p + i; /* 第 i 个学生、当前这门课的成绩 */
      if (*q < 60) {
        count++;
      }
      sum += *q;
    }

    if (count >= 2) {
      cout << "No：" << i + 1; /* 学号 = 列下标 + 1 */
      for (p = score; p < score + SCORE_NUM; p++) {
        cout << " " << *(*p + i);
      }
      cout << " 平均：" << sum / SCORE_NUM << endl;
    }
  }
}

/***************************************************************************
  函数名称：good
  功    能：找出平均成绩在 90 分以上（含 90）或全部课程成绩在 85 分
            以上（含 85）的学生
  输入参数：int (*score)[STUDENT_NUM]
  返 回 值：无
  说    明：只定义 3 个简单变量 + 1 个行指针变量 + 1 个简单指针变量
***************************************************************************/
void good(int (*score)[STUDENT_NUM]) {
  int i;                 /* 简单变量：学生列下标 */
  int count;             /* 简单变量：低于 85 分的门数 */
  double sum;            /* 简单变量：总分 */
  int (*p)[STUDENT_NUM]; /* 行指针 */
  int *q;                /* 简单指针 */

  cout << "平均90以上或全部85以上的学生：" << endl;

  for (i = 0; i < STUDENT_NUM; i++) {
    count = 0;
    sum = 0;
    for (p = score; p < score + SCORE_NUM; p++) {
      q = *p + i;
      sum += *q;
      if (*q < 85) {
        count++;
      }
    }

    if (sum / SCORE_NUM >= 90 || count == 0) {
      cout << "No：" << i + 1;
      for (p = score; p < score + SCORE_NUM; p++) {
        cout << " " << *(*p + i);
      }
      cout << " 平均：" << sum / SCORE_NUM << endl;
    }
  }
}

/***************************************************************************
  函数名称：main
  功    能：输出初始信息，并依次调用 average、fail、good 三个函数
  输入参数：无
  返 回 值：0
  说    明：除预置二维数组外，只定义 1 个行指针变量 + 1 个简单指针变量
***************************************************************************/
int main() {
  int a[SCORE_NUM][STUDENT_NUM] = {
      {91, 92, 93, 97},  // 第1-4个学生的第1门课成绩
      {81, 82, 83, 85},  // 第1-4个学生的第2门课成绩
      {71, 72, 99, 87},  // 第1-4个学生的第3门课成绩
      {61, 32, 80, 91},  // 第1-4个学生的第4门课成绩
      {51, 52, 95, 88}}; // 第1-4个学生的第5门课成绩

  int (*p)[STUDENT_NUM]; /* 行指针：一行一门课 */
  int *q;                /* 简单指针：一行内逐个学生 */

  cout << "初始信息：" << endl;
  for (p = a; p < a + SCORE_NUM; p++) /* 行循环用行指针 */
  {
    cout << "No.1-4学生的第" << p - a + 1 << "门课的成绩：";
    for (q = *p; q < *p + STUDENT_NUM; q++) {
      cout << *q << " ";
    }
    cout << endl;
  }

  cout << endl;
  average(a); /* 求第一门课的平均分 */
  cout << endl;
  fail(a); /* 两门以上不及格的学生 */
  cout << endl;
  good(a); /* 平均 90 以上或全部 85 以上 */

  return 0;
}